import { type ProjectStructure } from '../../../store/types';
import { generateAsciiTree, normalizePath } from './commandEngine';

// Export as ASCII Tree string
export function exportAsAsciiTree(project: ProjectStructure): string {
  return generateAsciiTree(project.rootName || project.name, project.nodes);
}

// Export as Markdown Documentation
export function exportAsMarkdown(project: ProjectStructure): string {
  const tree = exportAsAsciiTree(project);
  const folders = project.nodes.filter((n) => n.type === 'folder').length;
  const files = project.nodes.filter((n) => n.type === 'file').length;

  let md = `# ${project.name}\n\n`;
  if (project.description) {
    md += `> ${project.description}\n\n`;
  }
  md += `## Architecture Overview\n\n- **Root**: \`${project.rootName}\`\n- **Folders**: ${folders}\n- **Files**: ${files}\n- **Template**: ${project.templateType || 'Custom'}\n\n`;
  md += `## Project Tree\n\n\`\`\`text\n${tree}\n\`\`\`\n\n`;

  const filesWithContent = project.nodes.filter((n) => n.type === 'file' && n.content && n.content.trim().length > 0);
  if (filesWithContent.length > 0) {
    md += `## File Specifications & Boilerplates\n\n`;
    filesWithContent.forEach((file) => {
      const ext = file.extension || 'text';
      md += `### \`${file.path}\`\n\n\`\`\`${ext}\n${file.content}\n\`\`\`\n\n`;
    });
  }

  return md;
}

// Export as Bash Shell Script
export function exportAsBashScript(project: ProjectStructure): string {
  const root = project.rootName || 'my-project';
  const folders = project.nodes.filter((n) => n.type === 'folder');
  const files = project.nodes.filter((n) => n.type === 'file');

  const lines: string[] = [
    '#!/usr/bin/env bash',
    `# Scaffold script for ${project.name}`,
    `# Generated by Personal HQ Project Architect`,
    '',
    `mkdir -p "${root}"`,
    `cd "${root}" || exit 1`,
    '',
    '# Create directories',
  ];

  folders.forEach((folder) => {
    lines.push(`mkdir -p "${folder.path}"`);
  });

  lines.push('', '# Create files');
  files.forEach((file) => {
    if (file.content && file.content.trim().length > 0) {
      // Escape EOF safely
      const escaped = file.content.replace(/\\/g, '\\\\').replace(/\$/g, '\\$');
      lines.push(`cat << 'EOF' > "${file.path}"\n${escaped}\nEOF`);
    } else {
      lines.push(`touch "${file.path}"`);
    }
  });

  lines.push('', 'echo "🚀 Project ${project.name} structure created successfully!"');
  return lines.join('\n');
}

// Export as PowerShell Script
export function exportAsPowerShellScript(project: ProjectStructure): string {
  const root = project.rootName || 'my-project';
  const folders = project.nodes.filter((n) => n.type === 'folder');
  const files = project.nodes.filter((n) => n.type === 'file');

  const lines: string[] = [
    `# Scaffold script for ${project.name}`,
    `# Generated by Personal HQ Project Architect`,
    `# Run with: powershell -ExecutionPolicy Bypass -File .\\setup.ps1`,
    '',
    `$Root = "${root}"`,
    `if (!(Test-Path -Path $Root)) { New-Item -ItemType Directory -Path $Root -Force | Out-Null }`,
    `Set-Location -Path $Root`,
    '',
    '# Create directories',
  ];

  folders.forEach((folder) => {
    lines.push(`if (!(Test-Path -Path "${folder.path}")) { New-Item -ItemType Directory -Path "${folder.path}" -Force | Out-Null }`);
  });

  lines.push('', '# Create files');
  files.forEach((file) => {
    if (file.content && file.content.trim().length > 0) {
      const escaped = file.content.replace(/`/g, '``').replace(/"/g, '`"');
      lines.push(`@" \n${escaped}\n"@ | Out-File -FilePath "${file.path}" -Encoding utf8 -Force`);
    } else {
      lines.push(`if (!(Test-Path -Path "${file.path}")) { New-Item -ItemType File -Path "${file.path}" -Force | Out-Null }`);
    }
  });

  lines.push('', 'Write-Host "🚀 Project created successfully in $Root" -ForegroundColor Green');
  return lines.join('\n');
}

